import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import path from 'path';

// Today's date in the UK, as YYYY-MM-DD. Blog posts dated after this are
// scheduled: they are left out of the build until a build runs on or after
// their date (see src/lib/blog.ts and .github/workflows/weekly-blog.yml).
// BLOG_BUILD_DATE overrides it for testing; BLOG_SHOW_SCHEDULED=1 shows
// every scheduled post, for previewing the queue locally.
function ukToday(): string {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Europe/London',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(new Date());
}

// https://vitejs.dev/config/
// NOTE: The sitemap is generated by scripts/prerender.mjs from the same `routes`
// array used to prerender pages (single source of truth), with tiered priorities.
// robots.txt is served statically from public/robots.txt.
export default defineConfig(({ mode }) => {
  const isSSR = mode === 'ssr';

  return {
    define: {
      __BLOG_BUILD_DATE__: JSON.stringify(process.env.BLOG_BUILD_DATE || ukToday()),
      __BLOG_SHOW_SCHEDULED__: JSON.stringify(process.env.BLOG_SHOW_SCHEDULED === '1'),
    },
    plugins: [
      react(),
    ],
    resolve: {
      alias: isSSR ? [
        {
          find: 'gsap/ScrollTrigger',
          replacement: path.resolve(__dirname, 'src/lib/gsap-scroll-trigger-ssr-mock.ts'),
        },
        {
          find: '@gsap/react',
          replacement: path.resolve(__dirname, 'src/lib/gsap-react-ssr-mock.ts'),
        },
        {
          find: 'gsap',
          replacement: path.resolve(__dirname, 'src/lib/gsap-ssr-mock.ts'),
        },
      ] : [],
    },
    ssr: {
      noExternal: ['react-helmet-async'],
    },
    optimizeDeps: {
      exclude: ['lucide-react'],
    },
    server: {
      proxy: {
        '/api': {
          target: 'http://localhost:3000',
          changeOrigin: true,
          rewrite: (path) => path,
        },
      },
    },
  };
});
